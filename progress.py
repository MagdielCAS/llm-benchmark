"""
progress.py — Persistence layer for benchmark run state.

All progress is stored as markdown files with YAML frontmatter so the
benchmark can be interrupted and resumed at any time.  The ``results/``
directory layout is:

::

    results/
    ├── answers/
    │   └── <model>__<prompt_id>.md   # one per (model, prompt) pair
    ├── scores/
    │   └── <scorer>__<pid>__<mode>.md  # one per (scorer, prompt, mode)
    ├── user_picks.md               # the user’s manual selections
    └── report.md                   # generated by reporter.py

Skip-logic contract
-------------------
An answer is considered **done** when its frontmatter contains
``status: done``.  A score is considered done simply by the file
existing.  This means a partial/crashed write will be retried on the
next run.
"""

import os
import re
from datetime import datetime, timezone
from pathlib import Path
from typing import Optional

import yaml

RESULTS_DIR = Path(__file__).parent / "results"
ANSWERS_DIR = RESULTS_DIR / "answers"
SCORES_DIR = RESULTS_DIR / "scores"
USER_PICKS_FILE = RESULTS_DIR / "user_picks.md"


def _ensure_dirs() -> None:
    ANSWERS_DIR.mkdir(parents=True, exist_ok=True)
    SCORES_DIR.mkdir(parents=True, exist_ok=True)


def _now() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def _write_md(path: Path, frontmatter: dict, body: str = "") -> None:
    """Write a markdown file with YAML frontmatter."""
    path.parent.mkdir(parents=True, exist_ok=True)
    fm_str = yaml.dump(frontmatter, allow_unicode=True, sort_keys=False).strip()
    content = f"---\n{fm_str}\n---\n\n{body}"
    path.write_text(content, encoding="utf-8")


def _read_frontmatter(path: Path) -> tuple[dict, str]:
    """Parse YAML frontmatter from a markdown file. Returns (meta, body)."""
    text = path.read_text(encoding="utf-8")
    match = re.match(r"^---\s*\n(.*?)\n---\s*\n?(.*)", text, re.DOTALL)
    if not match:
        return {}, text
    meta = yaml.safe_load(match.group(1)) or {}
    body = match.group(2).strip()
    return meta, body


# ---------------------------------------------------------------------------
# Answer files
# ---------------------------------------------------------------------------

def answer_path(model: str, prompt_id: str) -> Path:
    """Return the canonical ``Path`` for an answer file.

    Colons and slashes in model names (e.g. ``mistral:7b``) are replaced
    with underscores so the filename is safe on all filesystems.
    """
    safe_model = model.replace(":", "_").replace("/", "_")
    return ANSWERS_DIR / f"{safe_model}__{prompt_id}.md"


def save_answer(
    model: str,
    prompt_id: str,
    category: str,
    label: str,
    user_prompt: str,
    answer: str,
    tokens: int,
    duration_s: float,
) -> None:
    """Persist a model answer as a markdown file with YAML frontmatter.

    Overwrites any previous file for the same ``(model, prompt_id)`` pair.
    After writing, :func:`is_answer_done` will return ``True`` for this pair.
    """
    _ensure_dirs()
    path = answer_path(model, prompt_id)
    meta = {
        "model": model,
        "category": category,
        "prompt_id": prompt_id,
        "label": label,
        "status": "done",
        "tokens": tokens,
        "duration_s": duration_s,
        "timestamp": _now(),
    }
    body = f"## Prompt\n\n{user_prompt}\n\n## Answer\n\n{answer}"
    _write_md(path, meta, body)


def is_answer_done(model: str, prompt_id: str) -> bool:
    """Return ``True`` if a completed answer exists for this (model, prompt_id) pair."""
    path = answer_path(model, prompt_id)
    if not path.exists():
        return False
    meta, _ = _read_frontmatter(path)
    return meta.get("status") == "done"


def load_answer(model: str, prompt_id: str) -> Optional[str]:
    """Load the answer text from disk, or ``None`` if not found.

    Only the content under the ``## Answer`` heading is returned;
    the prompt text stored in ``## Prompt`` is excluded.
    """
    path = answer_path(model, prompt_id)
    if not path.exists():
        return None
    _, body = _read_frontmatter(path)
    # Extract just the answer part
    match = re.search(r"## Answer\s*\n\n(.*)", body, re.DOTALL)
    if match:
        return match.group(1).strip()
    return body


def get_all_done_answers() -> list[dict]:
    """Return metadata for all completed answer files."""
    _ensure_dirs()
    results = []
    for f in ANSWERS_DIR.glob("*.md"):
        meta, _ = _read_frontmatter(f)
        if meta.get("status") == "done":
            results.append(meta)
    return results


# ---------------------------------------------------------------------------
# Score files
# ---------------------------------------------------------------------------

def score_path(scoring_model: str, prompt_id: str, mode: str) -> Path:
    """Return the canonical ``Path`` for a score file.

    Parameters
    ----------
    scoring_model:
        Model acting as judge.
    prompt_id:
        ID of the prompt being scored.
    mode:
        ``'anonymous'`` or ``'named'``.
    """
    safe = scoring_model.replace(":", "_").replace("/", "_")
    return SCORES_DIR / f"{safe}__{prompt_id}__{mode}.md"


def save_score(
    scoring_model: str,
    prompt_id: str,
    mode: str,
    scores: dict[str, int],
    rationale: dict[str, str],
) -> None:
    """Persist a scoring result as a markdown file with YAML frontmatter.

    ``scores`` maps model name → integer score (1–10).
    ``rationale`` maps model name → free-text justification string.
    """
    _ensure_dirs()
    path = score_path(scoring_model, prompt_id, mode)
    meta = {
        "scoring_model": scoring_model,
        "prompt_id": prompt_id,
        "mode": mode,
        "scores": scores,
        "rationale": rationale,
        "timestamp": _now(),
    }
    _write_md(path, meta)


def is_score_done(scoring_model: str, prompt_id: str, mode: str) -> bool:
    """Return ``True`` if a score file exists for this (scorer, prompt, mode) triple."""
    return score_path(scoring_model, prompt_id, mode).exists()


def load_score(scoring_model: str, prompt_id: str, mode: str) -> Optional[dict]:
    """Load the frontmatter dict of a score file, or ``None`` if not found."""
    path = score_path(scoring_model, prompt_id, mode)
    if not path.exists():
        return None
    meta, _ = _read_frontmatter(path)
    return meta


def get_all_scores() -> list[dict]:
    """Return metadata for all score files."""
    _ensure_dirs()
    results = []
    for f in SCORES_DIR.glob("*.md"):
        meta, _ = _read_frontmatter(f)
        if meta:
            results.append(meta)
    return results


# ---------------------------------------------------------------------------
# User picks file
# ---------------------------------------------------------------------------

def save_user_picks(picks: list[dict]) -> None:
    """Save the user's manual selections."""
    _ensure_dirs()
    lines = ["# User Picks\n"]
    for pick in picks:
        lines.append(f"## {pick['prompt_id']}\n")
        lines.append(f"- **Category**: {pick['category']}\n")
        lines.append(f"- **Winner**: {pick['winner']}\n")
        lines.append(f"- **Timestamp**: {_now()}\n\n")
    USER_PICKS_FILE.write_text("".join(lines), encoding="utf-8")


def load_user_picks() -> list[dict]:
    """Load existing user picks if any."""
    if not USER_PICKS_FILE.exists():
        return []
    text = USER_PICKS_FILE.read_text(encoding="utf-8")
    picks = []
    blocks = re.split(r"^## ", text, flags=re.MULTILINE)[1:]
    for block in blocks:
        prompt_id = block.split("\n")[0].strip()
        cat_match = re.search(r"\*\*Category\*\*: (.+)", block)
        winner_match = re.search(r"\*\*Winner\*\*: (.+)", block)
        picks.append({
            "prompt_id": prompt_id,
            "category": cat_match.group(1).strip() if cat_match else "",
            "winner": winner_match.group(1).strip() if winner_match else "",
        })
    return picks


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def has_any_results() -> bool:
    """True if any answer or score files exist."""
    _ensure_dirs()
    return any(ANSWERS_DIR.iterdir()) or any(SCORES_DIR.iterdir())
